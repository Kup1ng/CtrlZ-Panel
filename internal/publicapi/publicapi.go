// Package publicapi derives the public API document from the tenant document (docs/specs/p3-endpoints.md 6.5, T-320).
//
// The public API is exactly the operations whose x-ctrlz-token is read or write, with the schemas they reach and a bearer security
// scheme. It is generated, never written by hand: api/public-openapi.yaml is the output of Generate over api/openapi.yaml, and a
// test fails when the committed file is not that output, so an operation cannot join or leave the public API without the file
// showing it. The panel renders the file at build into its documentation page and serves it for download.
package publicapi

import (
	"bytes"
	"errors"
	"fmt"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

// Header is the comment the file starts with.
const Header = "# Generated by tools/genpublicapi from api/openapi.yaml. Do not edit: go run ./tools/genpublicapi rewrites it, and a\n" +
	"# test fails when this file is not what that command writes.\n"

// tokenKey is the one x-ctrlz extension the public document keeps: it says what a token may do with the operation.
const tokenKey = "x-ctrlz-token"

const description = "The public API of Ctrl Z: the operations an API token may call.\n\n" +
	"Make a token in Preferences, API. A token is `read` or `write` for good, may be limited to some addresses, and lives 365 days. " +
	"Send it as `Authorization: Bearer ctz_...`. A `read` token cannot call an operation that changes anything. A request that carries " +
	"a session cookie as well is refused, and so is a token on an operation that is not in this document.\n\n" +
	"Errors are `Error` bodies. A token that is not live is `401 token_invalid`; `403 token_read_only`, `403 token_ip_not_allowed`, " +
	"`403 token_not_allowed` and `403 account_suspended` say why a live one was refused; `429 rate_limited` carries `Retry-After`.\n"

// Generate writes the public document for a tenant document.
func Generate(tenant []byte) ([]byte, error) {
	var src map[string]any
	if err := yaml.Unmarshal(tenant, &src); err != nil {
		return nil, fmt.Errorf("publicapi: %w", err)
	}
	paths, _ := src["paths"].(map[string]any)
	if paths == nil {
		return nil, errors.New("publicapi: the document has no paths")
	}
	comps, _ := src["components"].(map[string]any)
	kept := map[string]any{}
	used := map[string]bool{} // groups
	refs := newRefs()
	for path, item := range paths {
		pi, _ := item.(map[string]any)
		out := map[string]any{}
		for method, o := range pi {
			op, _ := o.(map[string]any)
			if !isMethod(method) || op == nil {
				continue
			}
			tok, _ := op[tokenKey].(string)
			if tok != "read" && tok != "write" {
				continue
			}
			pub := map[string]any{tokenKey: tok, "security": []any{map[string]any{"apiToken": []any{}}}}
			for _, k := range []string{"tags", "operationId", "summary", "description", "parameters", "requestBody", "responses"} {
				if v, ok := op[k]; ok {
					pub[k] = v
				}
			}
			for _, t := range asStrings(op["tags"]) {
				used[t] = true
			}
			refs.walk(pub)
			out[method] = pub
		}
		if len(out) > 0 {
			if v, ok := pi["parameters"]; ok {
				out["parameters"] = v
				refs.walk(v)
			}
			kept[path] = out
		}
	}
	if len(kept) == 0 {
		return nil, errors.New("publicapi: no operation takes a token")
	}
	components := map[string]any{"securitySchemes": map[string]any{"apiToken": map[string]any{
		"type": "http", "scheme": "bearer", "description": "An API token, `ctz_` and 64 characters."}}}
	// The parameters, responses and schemas the kept operations reach, and what those reach in turn.
	for refs.more() {
		kind, name := refs.next()
		group, _ := comps[kind].(map[string]any)
		v, ok := group[name]
		if !ok {
			return nil, fmt.Errorf("publicapi: #/components/%s/%s is referenced and not defined", kind, name)
		}
		refs.walk(v)
		g, _ := components[kind].(map[string]any)
		if g == nil {
			g = map[string]any{}
			components[kind] = g
		}
		g[name] = v
	}
	var tags []any
	for _, t := range asMaps(src["tags"]) {
		if n, _ := t["name"].(string); used[n] {
			tags = append(tags, t)
		}
	}
	info, _ := src["info"].(map[string]any)
	version, _ := info["version"].(string)
	doc := map[string]any{
		"openapi":    src["openapi"],
		"info":       map[string]any{"title": "Ctrl Z public API", "version": version, "description": description},
		"servers":    src["servers"],
		"tags":       tags,
		"paths":      kept,
		"components": components,
	}
	stripExtensions(doc)
	var buf bytes.Buffer
	buf.WriteString(Header)
	// The top level in the order a reader expects; the maps below are written with their keys sorted, so the output is stable.
	root := &yaml.Node{Kind: yaml.MappingNode}
	for _, k := range []string{"openapi", "info", "servers", "tags", "paths", "components"} {
		var v yaml.Node
		if err := v.Encode(doc[k]); err != nil {
			return nil, err
		}
		root.Content = append(root.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: k}, &v)
	}
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(root); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// Operations lists the operations of a document as "METHOD /path" with the token value each declares ("" for none declared).
func Operations(doc []byte) (map[string]string, error) {
	var src map[string]any
	if err := yaml.Unmarshal(doc, &src); err != nil {
		return nil, fmt.Errorf("publicapi: %w", err)
	}
	out := map[string]string{}
	paths, _ := src["paths"].(map[string]any)
	for path, item := range paths {
		pi, _ := item.(map[string]any)
		for method, o := range pi {
			if !isMethod(method) {
				continue
			}
			op, _ := o.(map[string]any)
			tok, _ := op[tokenKey].(string)
			out[strings.ToUpper(method)+" "+path] = tok
		}
	}
	return out, nil
}

// Check says the public document holds exactly the token operations of the tenant document, each with the value the tenant document
// gives it: an operation whose x-ctrlz-token is none in the public one, a token operation missing from it, or one that changed kind,
// fails. It reads the two documents, not the output of Generate, so it can fail on a file that was edited by hand.
func Check(public, tenant []byte) error {
	pub, err := Operations(public)
	if err != nil {
		return err
	}
	ten, err := Operations(tenant)
	if err != nil {
		return err
	}
	var problems []string
	for k, tok := range pub {
		switch want := ten[k]; {
		case tok != "read" && tok != "write":
			problems = append(problems, fmt.Sprintf("%s is in the public document with x-ctrlz-token %q", k, tok))
		case want != tok:
			problems = append(problems, fmt.Sprintf("%s is %q in the public document and %q in the tenant one", k, tok, want))
		}
	}
	for k, tok := range ten {
		if _, in := pub[k]; (tok == "read" || tok == "write") && !in {
			problems = append(problems, k+" takes a token and is missing from the public document")
		}
	}
	if len(problems) == 0 {
		return nil
	}
	sort.Strings(problems)
	return errors.New("publicapi: " + strings.Join(problems, "; "))
}

func isMethod(k string) bool {
	switch k {
	case "get", "put", "post", "delete", "patch":
		return true
	}
	return false
}

func asStrings(v any) []string {
	var out []string
	if l, ok := v.([]any); ok {
		for _, e := range l {
			if s, ok := e.(string); ok {
				out = append(out, s)
			}
		}
	}
	return out
}

func asMaps(v any) []map[string]any {
	var out []map[string]any
	if l, ok := v.([]any); ok {
		for _, e := range l {
			if m, ok := e.(map[string]any); ok {
				out = append(out, m)
			}
		}
	}
	return out
}

// stripExtensions removes every x-ctrlz-* key the public reader has no use for: the schemas carry the lints' marks (x-ctrlz-rowref),
// and the operations the pipeline's. The one kept is the token value of an operation.
func stripExtensions(v any) {
	switch t := v.(type) {
	case map[string]any:
		for k, c := range t {
			if strings.HasPrefix(k, "x-ctrlz-") && k != tokenKey {
				delete(t, k)
				continue
			}
			stripExtensions(c)
		}
	case []any:
		for _, c := range t {
			stripExtensions(c)
		}
	}
}

// refs is the closure of the references of the kept operations.
type refs struct {
	seen  map[string]bool
	queue [][2]string
}

func newRefs() *refs { return &refs{seen: map[string]bool{}} }

func (r *refs) more() bool { return len(r.queue) > 0 }

func (r *refs) next() (kind, name string) {
	h := r.queue[0]
	r.queue = r.queue[1:]
	return h[0], h[1]
}

// walk queues every "#/components/<kind>/<name>" reference found under v.
func (r *refs) walk(v any) {
	switch t := v.(type) {
	case map[string]any:
		for k, c := range t {
			if s, ok := c.(string); ok && k == "$ref" {
				if rest, ok := strings.CutPrefix(s, "#/components/"); ok {
					if kind, name, ok := strings.Cut(rest, "/"); ok && !r.seen[rest] {
						r.seen[rest] = true
						r.queue = append(r.queue, [2]string{kind, name})
					}
				}
				continue
			}
			r.walk(c)
		}
	case []any:
		for _, c := range t {
			r.walk(c)
		}
	}
}
