// Package migrategen expands the macros in migrations/postgres/src into the
// plain SQL files that goose applies.
//
// The spec asks for the tenant policy and the action-and-target column set to
// be written once and expanded at build time, so that sixty tables carry
// identical text and a reviewer reads each pattern once. The expanded files
// are committed, because the migrator embeds them and a migration must never
// change after it has been applied somewhere; a test regenerates them and
// fails on any difference.
package migrategen

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"
)

const header = "-- Code generated by tools/genmig from migrations/postgres/src/%s. DO NOT EDIT.\n-- Change the source file and run scripts/gen-migrations.sh.\n\n"

// catalogTables are the global tables whose grants are uniform: the node-facing
// and background roles read them and the writers maintain them. Which of them
// the tenant role may read is listed by hand in 0007, because it is a short,
// deliberate list.
func catalogTables() []string {
	return []string{
		"catalog_versions", "catalog_filter", "catalog_filter_mode", "catalog_filter_table",
		"catalog_service_category", "catalog_service", "catalog_service_domain",
		"catalog_service_alias", "catalog_protected_domains", "catalog_infra_denylist",
		"catalog_common_domains", "catalog_rewrites", "endpoint_types", "profile_presets",
	}
}

func funcs(seedDir string) template.FuncMap {
	return template.FuncMap{
		// seed expands migrations/seed/<name>.json into one INSERT, so seed data is reviewed as
		// data and the SQL cannot drift from it: genmig -check fails when either changes alone.
		"seed": func(name string) (string, error) { return seedSQL(seedDir, name) },
		"ts": func() string {
			return "created_at timestamptz NOT NULL DEFAULT now(),\n  updated_at timestamptz NOT NULL DEFAULT now()"
		},
		"tid": func() string {
			return "tenant_id uuid NOT NULL REFERENCES tenants (id) ON DELETE CASCADE"
		},
		"touch": func(table string) string {
			return fmt.Sprintf("CREATE TRIGGER touch_updated_at BEFORE UPDATE ON %s\n  FOR EACH ROW EXECUTE FUNCTION ctrlz.touch_updated_at();", table)
		},
		"rls":         rls,
		"rls_tenants": func() string { return rlsOn("tenants", "id") },
		"actionset":   actionSet,
		"grant": func(table, role, spec string) string {
			return fmt.Sprintf("SELECT pg_temp.grant_dsl('%s', 'ctrlz_%s', '%s');", table, role, spec)
		},
		"catalog_grants": func() string {
			var b strings.Builder
			for _, t := range catalogTables() {
				fmt.Fprintf(&b, "SELECT pg_temp.grant_dsl('%s', 'ctrlz_hub', 'S');\n", t)
				fmt.Fprintf(&b, "SELECT pg_temp.grant_dsl('%s', 'ctrlz_compiler', 'S');\n", t)
				fmt.Fprintf(&b, "SELECT pg_temp.grant_dsl('%s', 'ctrlz_worker', 'S I U');\n", t)
				fmt.Fprintf(&b, "SELECT pg_temp.grant_dsl('%s', 'ctrlz_admin', 'S I U');\n", t)
			}
			return strings.TrimRight(b.String(), "\n")
		},
	}
}

func rls(table string) string { return rlsOn(table, "tenant_id") }

// rlsOn is the one tenant policy. FORCE makes it apply to the table owner as
// well, so the migrator reads and writes nothing in a tenant table. The policy
// has no TO clause: it applies to PUBLIC, so a role added later is covered by
// default, and reach is limited by grants.
func rlsOn(table, col string) string {
	return fmt.Sprintf(`ALTER TABLE %[1]s ENABLE ROW LEVEL SECURITY;
ALTER TABLE %[1]s FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON %[1]s
  USING (%[2]s = ctrlz.current_tenant_id())
  WITH CHECK (%[2]s = ctrlz.current_tenant_id());`, table, col)
}

// actionSet emits the column definitions and the CHECK for an action and its
// target (R49). flags may contain "null" (the action may be unset) and
// "inherit" (the action may be inherit, which the table constrains further).
// The output ends with a comma, so a definition must follow it.
func actionSet(table, prefix, flags string) string {
	nullable := strings.Contains(flags, "null")
	inherit := strings.Contains(flags, "inherit")
	a, k, l := prefix+"action", prefix+"target_kind", prefix+"target_location_id"
	v4, v6, h := prefix+"target_ipv4", prefix+"target_ipv6", prefix+"target_host"
	notNull := " NOT NULL"
	if nullable {
		notNull = ""
	}
	noTargets := fmt.Sprintf("%s IS NULL AND %s IS NULL AND %s IS NULL AND %s IS NULL AND %s IS NULL", k, l, v4, v6, h)
	otherThan := func(keep ...string) string {
		all := map[string]bool{l: true, v4: true, v6: true, h: true}
		for _, kk := range keep {
			delete(all, kk)
		}
		var names []string
		for n := range all {
			names = append(names, n)
		}
		sort.Strings(names)
		var parts []string
		for _, n := range names {
			parts = append(parts, n+" IS NULL")
		}
		return strings.Join(parts, " AND ")
	}
	branches := []string{
		fmt.Sprintf("(%s IN ('block', 'bypass') AND %s)", a, noTargets),
		fmt.Sprintf("(%s = 'redirect' AND %s = 'location' AND %s IS NOT NULL AND %s)", a, k, l, otherThan(l)),
		fmt.Sprintf("(%s = 'redirect' AND %s IN ('auto', 'random') AND %s)", a, k, otherThan()),
		fmt.Sprintf("(%s = 'redirect' AND %s = 'ip' AND (%s IS NOT NULL OR %s IS NOT NULL) AND %s AND (%s IS NULL OR family(%s) = 4) AND (%s IS NULL OR family(%s) = 6))",
			a, k, v4, v6, otherThan(v4, v6), v4, v4, v6, v6),
		fmt.Sprintf("(%s = 'redirect' AND %s = 'host' AND %s IS NOT NULL AND %s)", a, k, h, otherThan(h)),
	}
	if inherit {
		branches = append(branches, fmt.Sprintf("(%s = 'inherit' AND %s)", a, noTargets))
	}
	if nullable {
		branches = append(branches, fmt.Sprintf("(%s IS NULL AND %s)", a, noTargets))
	}
	var b strings.Builder
	fmt.Fprintf(&b, "%s text%s,\n", a, notNull)
	fmt.Fprintf(&b, "  %s text,\n", k)
	fmt.Fprintf(&b, "  %s uuid REFERENCES locations (id),\n", l)
	fmt.Fprintf(&b, "  %s inet,\n", v4)
	fmt.Fprintf(&b, "  %s inet,\n", v6)
	fmt.Fprintf(&b, "  %s text,\n", h)
	// COALESCE: a CHECK passes on NULL, and with a nullable action every
	// branch above can come out NULL instead of false.
	fmt.Fprintf(&b, "  CONSTRAINT %s_%saction_set CHECK (COALESCE(\n    %s,\n    false)),", table, prefix, strings.Join(branches, "\n    OR "))
	return b.String()
}

// Expand expands the macros in one source file. The seed macro needs a directory, so it
// fails here; Generate uses ExpandWithSeed.
func Expand(name, src string) (string, error) { return ExpandWithSeed(name, src, "") }

// ExpandWithSeed is Expand with the directory that the seed macro reads its JSON files from.
func ExpandWithSeed(name, src, seedDir string) (string, error) {
	t, err := template.New(name).Funcs(funcs(seedDir)).Option("missingkey=error").Parse(src)
	if err != nil {
		return "", fmt.Errorf("migrategen: parse %s: %w", name, err)
	}
	var out bytes.Buffer
	if err := t.Execute(&out, nil); err != nil {
		return "", fmt.Errorf("migrategen: expand %s: %w", name, err)
	}
	s := out.String()
	if strings.Contains(s, "{{") {
		return "", fmt.Errorf("migrategen: %s still contains a macro after expansion", name)
	}
	return fmt.Sprintf(header, name) + s, nil
}

// Generate expands every .sql file in srcDir into outDir, returning the file
// names it wrote. With check set it writes nothing and returns an error naming
// each file whose committed text differs from the expansion.
func Generate(srcDir, outDir string, check bool) ([]string, error) {
	entries, err := os.ReadDir(srcDir)
	if err != nil {
		return nil, err
	}
	var names []string
	var stale []string
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".sql") {
			continue
		}
		src, err := os.ReadFile(filepath.Join(srcDir, e.Name()))
		if err != nil {
			return nil, err
		}
		out, err := ExpandWithSeed(e.Name(), string(src), filepath.Join(srcDir, "..", "..", "seed"))
		if err != nil {
			return nil, err
		}
		names = append(names, e.Name())
		dst := filepath.Join(outDir, e.Name())
		if check {
			have, err := os.ReadFile(dst)
			if err != nil || string(have) != out {
				stale = append(stale, e.Name())
			}
			continue
		}
		if err := os.WriteFile(dst, []byte(out), 0o644); err != nil {
			return nil, err
		}
	}
	// The migrator embeds every 0*.sql in outDir (migrations/postgres/embed.go),
	// so a file there with no source is applied but was never checked against a
	// macro expansion: a hand-written migration, or the output of a source that
	// was renamed or deleted. It fails the run in both modes.
	orphans, err := orphanOutputs(outDir, names)
	if err != nil {
		return nil, err
	}
	var problems []string
	if len(stale) > 0 {
		problems = append(problems, fmt.Sprintf("generated migrations are stale or missing: %s (run scripts/gen-migrations.sh)", strings.Join(stale, ", ")))
	}
	if len(orphans) > 0 {
		problems = append(problems, fmt.Sprintf("migrations with no source in %s: %s (a migration is written in src/ and expanded, never by hand)", srcDir, strings.Join(orphans, ", ")))
	}
	if len(problems) > 0 {
		return names, fmt.Errorf("migrategen: %s", strings.Join(problems, "; "))
	}
	return names, nil
}

// orphanOutputs lists the 0*.sql files of outDir that no source produced.
func orphanOutputs(outDir string, sources []string) ([]string, error) {
	entries, err := os.ReadDir(outDir)
	if err != nil {
		return nil, err
	}
	have := map[string]bool{}
	for _, n := range sources {
		have[n] = true
	}
	var out []string
	for _, e := range entries {
		if e.IsDir() || !strings.HasPrefix(e.Name(), "0") || !strings.HasSuffix(e.Name(), ".sql") {
			continue
		}
		if !have[e.Name()] {
			out = append(out, e.Name())
		}
	}
	return out, nil
}
