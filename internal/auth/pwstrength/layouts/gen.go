package layouts

import (
	"bytes"
	"fmt"
	"go/format"
)

// funcName is the generated function of a layout.
func funcName(name string) string {
	switch name {
	case "isiri9147":
		return "isiriKey"
	case "kbdfa":
		return "legacyKey"
	}
	return name + "Key"
}

// Generate returns the source of pwstrength's layouts_gen.go for the embedded data.
// A switch, not a map: the workspace rule bans package-level mutable state, and a
// switch is constant data the compiler checks for duplicate cases.
func Generate() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/auth/pwstrength/layouts/gen from the layout data files; DO NOT EDIT.\n")
	b.WriteString("// Run `go generate ./internal/auth/pwstrength`. TestLayoutTablesAreGenerated fails on drift.\n\n")
	b.WriteString("package pwstrength\n")
	for _, name := range Names() {
		l, err := Load(name)
		if err != nil {
			return nil, err
		}
		es, err := l.Entries()
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\n// %s reads a character of the %s layout as the US key it sits on.\n", funcName(name), name)
		b.WriteString("// A key of 0 is a combining mark that is dropped. ok is false for a character the\n// layout does not type.\n")
		fmt.Fprintf(&b, "func %s(r rune) (key rune, ok bool) {\n\tswitch r {\n", funcName(name))
		for _, e := range es {
			fmt.Fprintf(&b, "\tcase %#x: // %U, key %s\n\t\treturn %s, true\n", e.From, e.From, e.Key, quote(e.To))
		}
		b.WriteString("\t}\n\treturn 0, false\n}\n")
	}
	pts, err := USGrid()
	if err != nil {
		return nil, err
	}
	b.WriteString("\n// usGrid places a character of the US legend on the keyboard: the row (1 is the number\n// row) and the column of the key that types it, shifted or not. It is how a walk is\n// recognised by its shape; the positions come from the scan codes of the layout data.\n")
	b.WriteString("func usGrid(r rune) (row, col int, ok bool) {\n\tswitch r {\n")
	for _, p := range pts {
		fmt.Fprintf(&b, "\tcase %q:\n\t\treturn %d, %d, true\n", p.R, p.Row, p.Col)
	}
	b.WriteString("\t}\n\treturn 0, 0, false\n}\n")
	return format.Source(b.Bytes())
}

func quote(r rune) string {
	if r == 0 {
		return "0"
	}
	return fmt.Sprintf("%q", r)
}
