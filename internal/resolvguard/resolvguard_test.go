package resolvguard

import (
	"errors"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const head = "# Generated by Docker Engine.\n\nnameserver 127.0.0.11\nsearch ctrlz_backend\noptions ndots:0\n\n# Based on host file: '/etc/resolv.conf' (internal resolver)\n"

func TestCheckText(t *testing.T) {
	cases := []struct {
		name string
		conf string
		want error
	}{
		{"a pinned domestic resolver", head + "# ExtServers: [192.0.2.53]\n# Overrides: [nameservers]\n", nil},
		{"three pinned resolvers", head + "# ExtServers: [192.0.2.53 192.0.2.54 2001:db8::53]\n", nil},
		{"forward from the host namespace", head + "# ExtServers: [host(127.0.0.1)]\n", ErrHostForward},
		{"one of three from the host", head + "# ExtServers: [192.0.2.53 host(127.0.0.53)]\n", ErrHostForward},
		{"a loopback written without host()", head + "# ExtServers: [127.0.0.1]\n", ErrHostForward},
		{"an IPv6 loopback", head + "# ExtServers: [::1]\n", ErrHostForward},
		{"the unspecified address", head + "# ExtServers: [0.0.0.0]\n", ErrHostForward},
		{"the embedded resolver with no comment", head, errUnverifiable},
		{"an empty list", head + "# ExtServers: []\n", errUnverifiable},
		{"an entry that is no address", head + "# ExtServers: [resolver.example]\n", errUnverifiable},
		{"a plain resolv.conf outside Docker", "nameserver 127.0.0.53\noptions edns0\n", nil},
		{"an empty file", "", nil},
	}
	for _, c := range cases {
		if got := CheckText(c.conf); !errors.Is(got, c.want) {
			t.Errorf("%s: got %v, want %v", c.name, got, c.want)
		}
	}
}

func TestCheckNeverNamesTheAddress(t *testing.T) {
	err := CheckText(head + "# ExtServers: [host(127.0.0.1)]\n")
	if err == nil || len(err.Error()) == 0 {
		t.Fatal("no error")
	}
	for _, s := range []string{"127.0.0.1"} {
		if strings.Contains(err.Error(), s) {
			t.Errorf("the error names %q", s)
		}
	}
}

func TestCheckFile(t *testing.T) {
	dir := t.TempDir()
	if err := Check(filepath.Join(dir, "missing")); err != nil {
		t.Errorf("a missing file: %v", err)
	}
	p := filepath.Join(dir, "resolv.conf")
	if err := os.WriteFile(p, []byte(head+"# ExtServers: [host(127.0.0.1)]\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := Check(p); !errors.Is(err, ErrHostForward) {
		t.Errorf("a host forward in a file: %v", err)
	}
}
