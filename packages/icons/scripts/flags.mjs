// Reads packages/icons/flags/<CC>.svg and writes src/flagTable.generated.ts, a table of small element trees.
//
//   node scripts/flags.mjs           write the file
//   node scripts/flags.mjs --check   write nothing, fail if it is missing or out of date (CI)
//
// Spec 7.4 and 7.5, p2 open question 5. The flags are bundled: no request leaves the origin for one. They are inline SVG
// elements built by React from this table, not an <img> (the CSP's img-src is 'self' only) and not innerHTML.
//
// The source files are the 3x2 flags of the npm package `country-flag-icons` 1.6.20 (MIT, docs/licences/flags.md), minified, copied
// without change for the 249 codes of packages/i18n/src/countries.ts. Their drawing uses a fixed set of elements and attributes, and
// this script refuses any other, so a file that gains a script, a link, an id or a style cannot slip in through an update.
import {existsSync, readdirSync, readFileSync, writeFileSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const dir = join(root, "flags");
const target = join(root, "src/flagTable.generated.ts");

const TAGS = new Set(["svg", "g", "path", "circle", "ellipse"]);
// Attribute name in the file, and the React prop it becomes.
const ATTRS = new Map([
  ["d", "d"],
  ["fill", "fill"],
  ["cx", "cx"],
  ["cy", "cy"],
  ["r", "r"],
  ["rx", "rx"],
  ["ry", "ry"],
  ["stroke", "stroke"],
  ["stroke-width", "strokeWidth"],
  ["stroke-miterlimit", "strokeMiterlimit"],
  ["stroke-linejoin", "strokeLinejoin"],
  ["fill-rule", "fillRule"],
  ["clip-rule", "clipRule"],
  ["opacity", "opacity"],
  ["viewBox", "viewBox"],
]);
// `class` is ignored (the package uses it for its own CSS sprite), and `xmlns` is not needed for an inline svg.
const IGNORED = new Set(["class", "xmlns"]);
const VALUE = /^[#A-Za-z0-9 .,\-+MmLlHhVvCcSsQqTtAaZz]*$/;

const problems = [];
const fail = (where, what) => problems.push(`${where}: ${what}`);

function parse(source, where) {
  const tokens = [...source.matchAll(/<(\/?)([a-zA-Z]+)((?:\s+[a-zA-Z:-]+="[^"]*")*)\s*(\/?)>/g)];
  const stripped = source.replace(/<(\/?)([a-zA-Z]+)((?:\s+[a-zA-Z:-]+="[^"]*")*)\s*(\/?)>/g, "").trim();
  if (stripped !== "") fail(where, `has text or markup that is not an element: ${stripped.slice(0, 40)}`);
  const stack = [];
  let rootNode;
  for (const [, closing, tag, attrText, selfClosing] of tokens) {
    if (closing) {
      stack.pop();
      continue;
    }
    if (!TAGS.has(tag)) {
      fail(where, `element <${tag}> is not allowed`);
      continue;
    }
    const props = {};
    for (const [, name, value] of attrText.matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)) {
      if (IGNORED.has(name)) continue;
      const prop = ATTRS.get(name);
      if (!prop) {
        fail(where, `attribute ${name} on <${tag}> is not allowed`);
        continue;
      }
      if (!VALUE.test(value) || /https?:|url\(|javascript/i.test(value)) fail(where, `attribute ${name} has a value that is not allowed`);
      props[prop] = value;
    }
    const node = [tag, props, []];
    if (stack.length) stack[stack.length - 1][2].push(node);
    else rootNode = node;
    if (!selfClosing) stack.push(node);
  }
  if (stack.length) fail(where, "has an element that is not closed");
  if (!rootNode || rootNode[0] !== "svg") {
    fail(where, "does not start with <svg>");
    return undefined;
  }
  if (!rootNode[1].viewBox) fail(where, "has no viewBox");
  return rootNode;
}

const files = existsSync(dir) ? readdirSync(dir).filter((f) => /^[A-Z]{2}\.svg$/.test(f)).sort() : [];
if (files.length === 0) fail("flags/", "has no flag files");
const table = {};
for (const file of files) {
  const code = file.slice(0, 2);
  const node = parse(readFileSync(join(dir, file), "utf8").replace(/\r\n/g, "\n"), `flags/${file}`);
  if (node) table[code] = {viewBox: node[1].viewBox, children: node[2]};
}
if (!existsSync(join(dir, "LICENSE"))) fail("flags/LICENSE", "missing: the MIT notice has to ship with the flags");

const text = `// GENERATED by scripts/flags.mjs from flags/*.svg. Do not edit.
// ${files.length} flags, 3x2, from country-flag-icons 1.6.20 (MIT). See docs/licences/flags.md.
export type FlagNode = readonly [tag: string, props: Readonly<Record<string, string>>, children: readonly FlagNode[]];
export type FlagDrawing = {readonly viewBox: string; readonly children: readonly FlagNode[]};

export const FLAGS: Readonly<Record<string, FlagDrawing>> = ${JSON.stringify(table)};
`;

if (problems.length) {
  for (const p of problems) console.error(p);
  process.exit(1);
}
if (check) {
  const current = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== text) {
    console.error("src/flagTable.generated.ts is missing or out of date: run `pnpm --filter @ctrlz/icons flags`");
    process.exit(1);
  }
} else {
  writeFileSync(target, text);
  console.log(`wrote ${files.length} flags`);
}
